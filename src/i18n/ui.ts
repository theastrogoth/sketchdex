export type Translate = (text: string, values?: Record<string, string | number>) => string

/** A function giving the interface's text in `language`; text without a translation stays English. */
export function translator(language: Language): Translate {
  const index = ORDER.indexOf(language as (typeof ORDER)[number])
  return (text, values = {}) => {
    const translated = (index >= 0 ? STRINGS[text]?.[index] : undefined) ?? text
    return translated.replace(/\{(\w+)\}/g, (placeholder, name: string) => (name in values ? String(values[name]) : placeholder))
  }
}
